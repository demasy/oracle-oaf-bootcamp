--------------------------------------------------------------------------------
-- VERIFICATION QUERIES
--------------------------------------------------------------------------------

-- Count records
SELECT 'XX_JOBS' as table_name, COUNT(*) as record_count FROM XX_JOBS
UNION ALL
SELECT 'XX_POSITIONS', COUNT(*) FROM XX_POSITIONS;

-- Master-Detail Summary
SELECT 
    j.job_id,
    j.job_name,
    j.job_head_count,
    COUNT(p.position_id) as position_count,
    SUM(NVL(p.position_head_count, 0)) as total_position_headcount,
    CASE 
        WHEN j.effective_end_date IS NULL THEN 'Active'
        WHEN j.effective_end_date >= SYSDATE THEN 'Active'
        ELSE 'Inactive'
    END as job_status
FROM xx_jobs j
LEFT JOIN xx_positions p ON j.job_id = p.job_id
GROUP BY j.job_id, j.job_name, j.job_head_count, j.effective_end_date
ORDER BY j.job_id;

-- Active Jobs and Positions Summary
SELECT 
    COUNT(DISTINCT j.job_id) as active_jobs,
    COUNT(DISTINCT p.position_id) as active_positions,
    SUM(j.job_head_count) as total_job_headcount,
    SUM(p.position_head_count) as total_position_headcount
FROM xx_jobs j
LEFT JOIN xx_positions p ON j.job_id = p.job_id
WHERE (j.effective_end_date IS NULL OR j.effective_end_date >= SYSDATE)
  AND (p.effective_end_date IS NULL OR p.effective_end_date >= SYSDATE);

